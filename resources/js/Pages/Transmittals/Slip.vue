<script setup>
import { computed, reactive } from 'vue';
import { Head } from '@inertiajs/vue3';
import StaffLayout from '@/Layouts/StaffLayout.vue';
import PageHeader from '@/Components/UI/PageHeader.vue';
import Button from '@/Components/UI/Button.vue';
import Icon from '@/Components/UI/Icon.vue';
import PersonInput from '@/Components/Forms/PersonInput.vue';

/**
 * The routing slip, printed exactly as the legacy system printed it.
 *
 * Two layouts, as before: ESD returning finished documents to a field office
 * (letter on pre-printed paper: a blank band at the top, a five-column table
 * and a tiny "Report generated by ETTS." line) and a field office sending
 * applications to the Regional Office (plain letter, table titled Name /
 * Particulars / Document / Remarks). The wording, addressee and signatory are
 * defaults that the person printing can change here; nothing typed is stored.
 * Everything outside the sheet is hidden when printing.
 */
const props = defineProps({
    transmittal: { type: Object, required: true },
    items: { type: Array, required: true },
    defaults: { type: Object, required: true },
    base: { type: String, default: '/admin/transmittals' },
});

const down = props.transmittal.direction === 'ESD_TO_FO';

const slip = reactive({
    date: props.defaults.date,
    rsu: props.defaults.rsu ?? '',
    addressee: down ? '' : props.defaults.addressee,
    position: down ? '' : props.defaults.position,
    address: down ? '' : props.defaults.address,
    body: props.defaults.body,
    closing: props.defaults.closing,
    signatory: props.defaults.signatory ?? '',
    designation: props.defaults.designation ?? '',
});

// "Dear Director [lastname]" takes the addressee's last word.
const body = computed(() => {
    const lastName = slip.addressee.trim().split(/\s+/).pop() || '[lastname]';

    return slip.body.replace('[lastname]', lastName);
});

// The legacy slip printed a bracketed placeholder for anything left blank.
const shown = computed(() => ({
    addressee: slip.addressee.trim() || '[Addressee Name]',
    position: slip.position.trim() || '[Position]',
    address: slip.address.trim() || (down ? '[CSC Field Office Address]' : ''),
    rsu: slip.rsu.trim() || '[RSU]',
    body: body.value.trim() || 'We are transmitting the following documents for your reference and appropriate action:',
    closing: slip.closing.trim() || 'Very truly yours,',
    signatory: slip.signatory.trim() || '[Signatory Name]',
    designation: slip.designation.trim() || '[Designation]',
}));

const upper = (value) => (value ?? '').toUpperCase();

// One row per item, in the column order of the layout being printed.
const rows = computed(() =>
    props.items.map((item, index) => {
        const eligibility = item.eligibility ? ` - ${item.eligibility}` : '';
        const note = [item.is_manual ? '' : item.record_remarks, item.remarks].filter(Boolean).join('; ');

        return down
            ? {
                  no: index + 1,
                  name: upper(item.is_manual ? item.name : item.name),
                  type: item.is_manual ? item.doc_type : `${item.type ?? ''}${eligibility}`,
                  details: item.is_manual ? item.description : item.details,
                  remarks: note,
              }
            : {
                  no: index + 1,
                  name: item.name,
                  type: item.is_manual ? item.description : `${item.type ?? ''}${eligibility}`,
                  details: item.is_manual ? item.doc_type : '',
                  remarks: item.remarks ?? '',
              };
    }),
);

const print = () => window.print();

const fieldClass =
    'block w-full rounded-md border border-border-strong bg-surface px-3 py-2 text-sm text-text shadow-xs focus:border-primary focus:outline-none focus-visible:ring-2 focus-visible:ring-focus-ring';
</script>

<template>
    <Head :title="`Routing slip ${transmittal.number}`" />

    <StaffLayout>
        <div class="print:hidden">
            <PageHeader
                :title="`Routing slip ${transmittal.number}`"
                :breadcrumbs="[{ label: 'Dashboard', href: '/dashboard' }, { label: 'Transmittals', href: base }, { label: transmittal.number, href: `${base}/${transmittal.id}` }, { label: 'Slip' }]"
            >
                <template #actions>
                    <Button @click="print"><Icon name="printer" size="sm" />Print</Button>
                </template>
            </PageHeader>

            <div class="mb-6 grid max-w-5xl gap-4 rounded-lg border border-border bg-surface p-5 sm:grid-cols-2">
                <div><label for="s-date" class="mb-1 block text-xs font-semibold text-text-muted uppercase">Date</label><input id="s-date" v-model="slip.date" :class="fieldClass" /></div>
                <div><label for="s-rsu" class="mb-1 block text-xs font-semibold text-text-muted uppercase">{{ down ? 'RSU' : 'CSC RO' }}</label><input id="s-rsu" v-model="slip.rsu" :class="fieldClass" /></div>
                <div><label for="s-addressee" class="mb-1 block text-xs font-semibold text-text-muted uppercase">Addressee</label><PersonInput id="s-addressee" v-model="slip.addressee" placeholder="Name of the Director" :input-class="fieldClass" @pick="(p) => p.position && (slip.position = p.position)" /></div>
                <div><label for="s-position" class="mb-1 block text-xs font-semibold text-text-muted uppercase">Position</label><input id="s-position" v-model="slip.position" :class="fieldClass" /></div>
                <div class="sm:col-span-2"><label for="s-address" class="mb-1 block text-xs font-semibold text-text-muted uppercase">{{ down ? 'Field office address' : 'RO address' }}</label><input id="s-address" v-model="slip.address" :class="fieldClass" /></div>
                <div class="sm:col-span-2"><label for="s-body" class="mb-1 block text-xs font-semibold text-text-muted uppercase">Body</label><textarea id="s-body" v-model="slip.body" rows="3" :class="fieldClass" /></div>
                <div class="sm:col-span-2"><label for="s-closing" class="mb-1 block text-xs font-semibold text-text-muted uppercase">Closing</label><textarea id="s-closing" v-model="slip.closing" rows="3" :class="fieldClass" /></div>
                <div><label for="s-signatory" class="mb-1 block text-xs font-semibold text-text-muted uppercase">Signatory</label><PersonInput id="s-signatory" v-model="slip.signatory" :input-class="fieldClass" @pick="(p) => p.position && (slip.designation = p.position)" /></div>
                <div><label for="s-designation" class="mb-1 block text-xs font-semibold text-text-muted uppercase">Designation</label><input id="s-designation" v-model="slip.designation" :class="fieldClass" /></div>
            </div>
        </div>

        <!-- ESD to field office: pre-printed letterhead paper, so the date sits low on the page. -->
        <article v-if="down" class="slip slip-esd" aria-label="Routing slip">
            <div class="date-block">{{ slip.date }}</div>
            <div class="routing-block">
                <div class="routing-name">{{ shown.addressee }}</div>
                <div>{{ shown.position }}</div>
                <div v-if="transmittal.office?.name">{{ transmittal.office.name }}</div>
                <div>{{ shown.address }}</div>
            </div>
            <div class="body-block">{{ shown.body }}</div>
            <table>
                <thead>
                    <tr>
                        <th style="width: 5%; font-size: 8px">No.</th>
                        <th style="width: 25%; font-size: 7px">Name of Requesting Party</th>
                        <th style="width: 15%; font-size: 8px">Transaction</th>
                        <th style="width: 25%; font-size: 7px">Documents to be Released</th>
                        <th style="width: 25%; font-size: 8px">Remarks</th>
                    </tr>
                </thead>
                <tbody>
                    <tr v-if="!rows.length"><td colspan="5" style="text-align: center; padding: 15px">No transactions bundled in this transmittal.</td></tr>
                    <tr v-for="row in rows" :key="row.no">
                        <td style="text-align: center; font-size: 10px">{{ row.no }}</td>
                        <td style="font-size: 10px">{{ row.name }}</td>
                        <td style="font-size: 10px">{{ row.type }}</td>
                        <td style="font-size: 10px">{{ row.details }}</td>
                        <td style="font-size: 8px">{{ row.remarks }}</td>
                    </tr>
                </tbody>
            </table>
            <div class="generated">{{ transmittal.number }}. Report generated by ETTS.</div>
            <div class="closing-block">{{ shown.closing }}</div>
            <div class="signatory-block">
                <div class="signatory-name">{{ shown.signatory }}</div>
                <div>{{ shown.designation }}</div>
                <div>{{ shown.rsu }}</div>
            </div>
        </article>

        <!-- Field office to the Regional Office. -->
        <article v-else class="slip slip-fo" aria-label="Routing slip">
            <div>{{ slip.date }}</div>
            <br />
            <div>
                <b>{{ slip.addressee }}</b><br />
                {{ slip.position }}<br />
                {{ slip.rsu }}<br />
                {{ slip.address }}
            </div>
            <br />
            <div class="body-text">{{ slip.body.replace('[lastname]', slip.addressee.trim().split(/\s+/).pop() || '[lastname]') }}</div>
            <table>
                <thead>
                    <tr><th>No.</th><th>Name</th><th>Particulars</th><th>Document</th><th>Remarks</th></tr>
                </thead>
                <tbody>
                    <tr v-for="row in rows" :key="row.no">
                        <td style="text-align: center">{{ row.no }}</td>
                        <td>{{ row.name }}</td>
                        <td>{{ row.type }}</td>
                        <td>{{ row.details }}</td>
                        <td>{{ row.remarks }}</td>
                    </tr>
                </tbody>
            </table>
            <div class="closing-text">{{ slip.closing }}</div>
            <div class="sig"><b>{{ slip.signatory }}</b><br />{{ slip.designation }}</div>
        </article>
    </StaffLayout>
</template>

